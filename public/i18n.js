let locale = 'en-GB';
export const normaliseLocale = value => value === 'pt-BR' ? 'pt-BR' : 'en-GB';
export const getLocale = () => locale;
export function setLocale(value) { locale = normaliseLocale(value); return locale; }
export function t(message) { return locale === 'pt-BR' ? (messages[message] ?? message) : message; }
export const localeKey = 'shift-locale-v1';
export function readLocale(storage) { try { return normaliseLocale(storage?.getItem(localeKey)); } catch { return 'en-GB'; } }
export function saveLocale(storage, value) { setLocale(value); try { storage?.setItem(localeKey, locale); return true; } catch { return false; } }

// These markers exist only on authored shell controls; never on testimony or names.
export function translateShell(doc) {
  doc.documentElement.lang = getLocale();
  for (const node of doc.querySelectorAll('[data-i18n]')) { if (node.id !== 'confirm-accept' || !doc.getElementById('confirm-dialog')?.open) node.textContent = t(node.dataset.i18n); }
  for (const node of doc.querySelectorAll('[data-i18n-aria]')) node.setAttribute('aria-label', t(node.dataset.i18nAria));
}
